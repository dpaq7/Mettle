/**
 * Get all complications.
 */
export function getAllComplications(): Complication[] {
  return COMPLICATIONS;
}

/**
 * Get a complication by ID.
 */
export function getComplication(id: string): Complication | undefined {
  return COMPLICATIONS.find(c => c.id === id);
}

/**
 * Search complications by name (case-insensitive partial match).
 */
export function searchComplications(query: string): Complication[] {
  const lowerQuery = query.toLowerCase();
  return COMPLICATIONS.filter(c => c.name.toLowerCase().includes(lowerQuery));
}
